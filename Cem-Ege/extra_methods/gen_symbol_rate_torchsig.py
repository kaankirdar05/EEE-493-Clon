"""Labelled symbol-rate test frames from TorchSig's own modulators (run in .venv-torchsig).

TorchSig scene boxes do not store the symbol rate, so frames are generated by
calling TorchSig's modulators directly with known parameters:
  * constellation_modulator (PSK/QAM/ASK): built at 4 samples/symbol and resampled
    so that the symbol rate equals the nominal bandwidth -> Rs = bandwidth.
    Pulse shape drawn like TorchSig does: SRRC (roll-off 0.1-0.5) or rectangular.
  * fsk_modulator (FSK/GFSK/MSK/GMSK): Rs = bandwidth / gamma, where gamma is the
    random bandwidth-symbol product TorchSig draws; captured by wrapping its
    fsk_symbol_timing function during the call.
Then a random carrier phase, a small frequency offset and AWGN are added.

    ..\\.venv-torchsig\\Scripts\\python gen_symbol_rate_torchsig.py   -> D:\\data\\symbol_rate_torchsig.npz
"""

import numpy as np
import torchsig.signals.builders.fsk as fsk
from torchsig.signals.builders.constellation import constellation_modulator

FS, N = 1.0, 4096
CONST = ["bpsk", "qpsk", "8psk", "16qam", "64qam"]
FSK = [(2, "fsk"), (4, "fsk"), (2, "gfsk"), (2, "msk"), (2, "gmsk")]
SNRS = [0, 5, 10, 15, 20]

_captured = {}
_orig_timing = fsk.fsk_symbol_timing


def _timing(*a, **k):
    gamma, sps = _orig_timing(*a, **k)
    _captured["gamma"] = gamma
    return gamma, sps


fsk.fsk_symbol_timing = _timing


def main(per_cell=60, seed=0):
    rng = np.random.default_rng(seed)
    X, rs, cls, snr, pulse = [], [], [], [], []
    names = CONST + [f"{m}{t}" for m, t in FSK]
    for name in names:
        for s in SNRS:
            made = 0
            while made < per_cell:
                if name in CONST:
                    bw = rng.uniform(0.05, 0.30)
                    ps = "srrc" if rng.integers(0, 2) == 0 else "rectangular"
                    x = constellation_modulator(name, ps, bw, FS, N, rng.uniform(0.1, 0.5) if ps == "srrc" else None, rng)
                    r = bw
                else:
                    m, t = next((m, t) for m, t in FSK if f"{m}{t}" == name)
                    bw = rng.uniform(0.08, 0.45)
                    x = fsk.fsk_modulator(m, t, bw, FS, N, rng)
                    r = bw / _captured["gamma"]
                    ps = t
                if not (1 / 25 <= r <= 1 / 2.5):   # estimator search range: 2.5-25 samples/symbol
                    continue
                x = np.asarray(x, complex)
                x = x / np.sqrt(np.mean(np.abs(x) ** 2))
                x = x * np.exp(1j * (rng.uniform(0, 2 * np.pi) + 2 * np.pi * rng.uniform(-0.01, 0.01) * np.arange(N)))
                x = x + np.sqrt(10 ** (-s / 10) / 2) * (rng.standard_normal(N) + 1j * rng.standard_normal(N))
                X.append(x.astype(np.complex64)); rs.append(r); cls.append(name); snr.append(s); pulse.append(ps)
                made += 1
    np.savez(r"D:\data\symbol_rate_torchsig.npz", x=np.array(X), rs=np.array(rs), cls=np.array(cls),
             snr=np.array(snr), pulse=np.array(pulse))
    print(f"{len(X)} frames, classes {names}")


if __name__ == "__main__":
    main()
